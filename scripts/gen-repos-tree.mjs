#!/usr/bin/env node
// Render this hub's repo tree (00_repos-tree/) from the git-repos-master submodule: the master's A0_repos-tree/dist/repos-tree.json
// filtered to the repos of kind html (00_repos-tree/src/filter.json). There is no separate list: the master is the only source.
//
//   node scripts/gen-repos-tree.mjs            src -> dist -> root: 00_repos-tree/dist/repos-tree.{json,md,html,xml,canvas}, copied to the
//                                              repo root (real files, same names)
//   node scripts/gen-repos-tree.mjs --check    write nothing; exit 1 when dist or the root copies differ from a fresh render
//
// Bump the data: `git submodule update --init --remote git-repos-master && node scripts/gen-repos-tree.mjs`, commit the gitlink and the outputs.
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = '00_repos-tree/dist';
const EXTS = ['json', 'md', 'html', 'xml', 'canvas'];
const cfg = JSON.parse(readFileSync(join(ROOT, '00_repos-tree/src/filter.json'), 'utf8'));
const MASTER = join(ROOT, 'git-repos-master');
const srcJson = join(ROOT, cfg.source);
if (!existsSync(srcJson)) { console.error(`${cfg.source} missing: run git submodule update --init git-repos-master`); process.exit(2); }

// the master's own renderer renders any (filtered) repos-tree json with the master's templates
const R = createRequire(join(MASTER, '0_registry/'))('./render-repos-tree.js');
const m = JSON.parse(readFileSync(srcJson, 'utf8'));
const prune = (o) => {
  const kids = (o.children || []).map(prune).filter(Boolean);
  if (o.node === 'group') return kids.length ? { ...o, children: kids } : null;
  return o[cfg.flag] || kids.length ? { ...o, children: kids } : null;
};
const tree = prune(m.tree);
let count = 0; (function w(o) { if (o.node !== 'group') count++; (o.children || []).forEach(w); })(tree);
const j = { ...m, _doc: `GENERATED by scripts/gen-repos-tree.mjs from the git-repos-master submodule (${cfg.source}) filtered to kind ${cfg.kind}. DO NOT EDIT.`, count, tree };
const rendered = R.renderFrom(JSON.stringify(j, null, 2) + '\n');
const out = { json: JSON.stringify(j, null, 2) + '\n' };
for (const e of EXTS.slice(1)) out[e] = rendered[`A0_repos-tree/dist/repos-tree.${e}`];

const NOTE = 'generated by scripts/gen-repos-tree.mjs - edit 00_repos-tree/src or the git-repos-master submodule, never this copy';
const stamp = (ext, t) => ext === 'md' ? t.replace(/^(---\n[\s\S]*?\n---\n)/, `$1<!-- ${NOTE} -->\n`)
  : ext === 'html' ? t.replace(/^(<!DOCTYPE html>\n)/i, `$1<!-- ${NOTE} -->\n`) : t;
const want = {};
for (const e of EXTS) { want[`${OUT}/repos-tree.${e}`] = out[e]; want[`repos-tree.${e}`] = stamp(e, out[e]); }

const check = process.argv.includes('--check');
let bad = 0;
for (const [f, t] of Object.entries(want)) {
  const fp = join(ROOT, f), cur = existsSync(fp) ? readFileSync(fp, 'utf8') : null;
  if (cur === t) continue;
  if (check) { console.error(`${f} differs from a fresh render (run node scripts/gen-repos-tree.mjs)`); bad = 1; continue; }
  mkdirSync(dirname(fp), { recursive: true }); writeFileSync(fp, t); console.log(`wrote ${f}`);
}
if (!bad) console.log(`${check ? 'checked' : 'rendered'} 00_repos-tree: ${count} nodes of kind ${cfg.kind} from the git-repos-master pin`);
process.exit(bad);
